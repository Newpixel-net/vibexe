// Escape single quotes for SQL
function sqlEscape(str) {
  return str.replace(/'/g, "''");
}

let sql = '-- Scene Template Seeds for Feature Bank\n';
sql += '-- Generated by tools/generate-scene-seed-sql.mjs\n';
sql += '-- Run via: psql -U vibexe -d vibexe -f tools/seed-scene-templates.sql\n\n';

// Delete existing scene templates first (idempotent)
sql += "DELETE FROM feature_bank_snippets WHERE id IN ('platformer-base', 'runner-base', 'puzzle-base', 'shooter-base');\n\n";

for (const tpl of templates) {
  const code = readFileSync(join(__dirname, 'scene-templates', tpl.file), 'utf-8');

  sql += `INSERT INTO feature_bank_snippets (id, name, description, category, type, engine, version, keywords, parameters, dependencies, genres, code, is_built_in, is_verified)\nVALUES (\n`;
  sql += `  '${tpl.id}',\n`;
  sql += `  '${sqlEscape(tpl.name)}',\n`;
  sql += `  '${sqlEscape(tpl.description)}',\n`;
  sql += `  'Scene Templates',\n`;
  sql += `  'scene',\n`;
  sql += `  '2d',\n`;
  sql += `  '1.0.0',\n`;
  sql += `  '${JSON.stringify(tpl.keywords)}'::jsonb,\n`;
  sql += `  '${JSON.stringify(tpl.parameters)}'::jsonb,\n`;
  sql += `  '[]'::jsonb,\n`;
  sql += `  '${JSON.stringify(tpl.genres)}'::jsonb,\n`;
  sql += `  '${sqlEscape(code)}',\n`;
  sql += `  true,\n`;
  sql += `  true\n`;
  sql += `);\n\n`;
}

